export type ToolsMessageKey = keyof typeof englishMessages;
export const toolsT = createTranslator(englishMessages);

interface ToolIssue extends ValidationIssue {
  messageKey?: ToolsMessageKey;
  params?: Record<string, string | number>;
}

export function toolIssue(path: string, messageKey: ToolsMessageKey, params?: ToolIssue['params']): ToolIssue {
  return { path, messageKey, ...(params ? { params } : {}), message: toolsT(messageKey, params) };
}

// Only tool-owned messages are translated. Paths, parameters and model values stay verbatim.
export function issueText(issue: ValidationIssue): string {
  const value = issue as ToolIssue;
  const key = value.messageKey ?? value.message;
  return Object.prototype.hasOwnProperty.call(englishMessages, key)
    ? toolsT(key as ToolsMessageKey, value.params) : value.message;
}

export function localizeIssue(issue: ValidationIssue): ToolIssue {
  const value = issue as ToolIssue;
  const key = value.messageKey ?? value.message;
  return Object.prototype.hasOwnProperty.call(englishMessages, key)
    ? { ...value, messageKey: key as ToolsMessageKey, message: issueText(value) } : value;
}
